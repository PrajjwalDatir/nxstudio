"use client";

import React, { createContext, useContext, useEffect, useState, useCallback } from "react";

export interface ProjectData {
  name: string;
  mission: string;
  stack: string;
  constraints: string;
  audience: string;
}

interface ProtocolContextType {
  data: ProjectData;
  updateField: (field: keyof ProjectData, value: string) => void;
  compiledProtocol: string;
  clearData: () => void;
}

const defaultData: ProjectData = {
  name: "",
  mission: "",
  stack: "",
  constraints: "",
  audience: "",
};

const STORAGE_KEY = "nx-studio-project";

const ProtocolContext = createContext<ProtocolContextType | null>(null);

export function useProtocol() {
  const context = useContext(ProtocolContext);
  if (!context) {
    throw new Error("useProtocol must be used within ProtocolProvider");
  }
  return context;
}

function compileProtocol(data: ProjectData): string {
  if (!data.name && !data.mission && !data.stack && !data.constraints && !data.audience) {
    return `# COG PROTOCOL
# ---------------------------------------------------
# Fill out the form to generate your AI context file
# ---------------------------------------------------

> Waiting for input...`;
  }

  const name = data.name || "Untitled";
  const nameUpper = name.toUpperCase();
  const nameLower = name.toLowerCase().replace(/\s+/g, "-");
  
  // Parse stack into array
  const stackItems = data.stack
    ? data.stack.split(",").map(s => s.trim()).filter(Boolean)
    : ["Not specified"];
  
  // Parse constraints into array
  const constraintItems = data.constraints
    ? data.constraints.split(",").map(c => c.trim()).filter(Boolean)
    : ["None specified"];

  return `# COG: ${nameUpper} INITIALIZATION PROTOCOL
# ---------------------------------------------------
# MISSION: ${data.mission || "Define your mission"}
# STATUS: Active
# ---------------------------------------------------

You are Cog, the initialization agent for the ${name} system.
Your goal is to scaffold the project environment based on the following DNA.

**PROJECT DNA:**
- **Name:** ${name}
- **Stack:** ${stackItems.join(", ")}
- **Constraint:** ${constraintItems.join("; ")}
- **Audience:** ${data.audience || "Not specified"}

**ACTION PLAN:**
1. Read and understand the project mission and constraints.
2. When writing code, use the defined technology stack.
3. Enforce all constraints before proposing solutions.
4. Optimize every decision for the target audience.

---

### GUARDRAILS

${constraintItems.map((c, i) => `${i + 1}. **${c}**`).join("\n")}

---

### SYSTEM PROMPT

# ${nameUpper} SYSTEM PROMPT

You are an expert developer working on **${name}**.

**PRIMARY DIRECTIVE:**
${data.mission || "No mission defined."}

**BEHAVIOR:**
- When asked for UI, assume: ${stackItems.slice(0, 2).join(" + ") || "default stack"}.
- When asked for logic, enforce constraints: ${constraintItems[0] || "none"}.
- If a request violates constraints, STOP and explain why.

**COMMANDS:**
- \`${nameLower}-init\`: Re-read this protocol.
- \`${nameLower}-status\`: Confirm project context.

---
*Generated by Nx Studio*`;
}

export function ProtocolProvider({ children }: { children: React.ReactNode }) {
  const [data, setData] = useState<ProjectData>(defaultData);
  const [isHydrated, setIsHydrated] = useState(false);

  // Load from localStorage on mount
  useEffect(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) {
      try {
        const parsed = JSON.parse(stored);
        setData(parsed);
      } catch (e) {
        console.error("Failed to parse stored data:", e);
      }
    }
    setIsHydrated(true);
  }, []);

  // Save to localStorage on change
  useEffect(() => {
    if (isHydrated) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    }
  }, [data, isHydrated]);

  const updateField = useCallback((field: keyof ProjectData, value: string) => {
    setData((prev) => ({ ...prev, [field]: value }));
  }, []);

  const clearData = useCallback(() => {
    setData(defaultData);
    localStorage.removeItem(STORAGE_KEY);
  }, []);

  const compiledProtocol = compileProtocol(data);

  return (
    <ProtocolContext.Provider value={{ data, updateField, compiledProtocol, clearData }}>
      {children}
    </ProtocolContext.Provider>
  );
}
